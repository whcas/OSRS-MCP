/// Instructions shown to clients that surface server guidance.
const INSTRUCTIONS: &str = "Read-only advisory server for Old School RuneScape Hardcore \
worlds. It never performs in-game actions. Call `server_info` to see the version and \
capabilities. Market tools read Hardcore Grand Exchange data only and report where and \
when it was retrieved; they never substitute standard-world data.";

/// The OSRS MCP server.
#[derive(Debug, Clone)]
pub struct OsrsMcpServer {
    tool_router: ToolRouter<Self>,
    market: Arc<dyn MarketData>,
    export_source: Arc<dyn ExportSource>,
}

impl OsrsMcpServer {
    /// Creates a server with all tools registered, reading Hardcore market data
    /// from the live prices API and with no `RuneLite` export directory
    /// configured; see [`with_export_source`](Self::with_export_source).
    /// Construction performs no network request.
    ///
    /// # Errors
    ///
    /// Returns [`ConfigError`] if the market client cannot be built.
    pub fn new() -> Result<Self, ConfigError> {
        let client = HardcoreClient::new(ClientConfig::default())?;
        Ok(Self::with_market(Arc::new(client)))
    }

    /// Creates a server that reads market data from `market`. The production
    /// path is [`new`](Self::new); this exists so the market source can be
    /// injected at the service boundary.
    fn with_market(market: Arc<dyn MarketData>) -> Self {
        Self {
            tool_router: Self::info_router()
                + Self::character_router()
                + Self::containers_router()
                + Self::quests_router()
                + Self::market_router()
                + Self::prices_router()
                + Self::profit_router(),
            market,
            export_source: Arc::new(LocalExportSource::unconfigured()),
        }
    }

    /// Sets where account tools read the local `RuneLite` export from.
    #[must_use]
    pub fn with_export_source(mut self, source: impl ExportSource + 'static) -> Self {
        self.export_source = Arc::new(source);
        self
    }
}

/// The MCP capabilities this server advertises. This is the single source for
/// both the `initialize` response and the `server_info` tool, so they cannot
/// drift apart.
fn server_capabilities() -> ServerCapabilities {
    ServerCapabilities::builder().enable_tools().build()
}

// The macro generates `async fn call_tool`/`list_tools` bodies that only
// delegate to the synchronous router; the lint cannot be satisfied in our code.
#[expect(
    clippy::unused_async_trait_impl,
    reason = "async trait methods are generated by rmcp's #[tool_handler] macro"
)]
#[tool_handler(router = self.tool_router)]
impl ServerHandler for OsrsMcpServer {
    fn get_info(&self) -> ServerConfig {
        let info = build_info();
        ServerConfig::new(server_capabilities())
            .with_server_info(Implementation::new(info.name, info.version))
            .with_instructions(INSTRUCTIONS)
    }
}

/// Serves MCP over the process's standard input and output until the client
/// disconnects.
///
/// Stdout carries protocol messages only; callers must send diagnostics to
/// stderr.
///
/// # Errors
///
/// Returns an error if the server cannot be configured, the MCP handshake fails or
/// the connection ends abnormally.
pub async fn serve_stdio() -> Result<(), ServeError> {
    let server = OsrsMcpServer::new()
        .map_err(|error| ServeError::Configuration(Box::new(error)))?
        .with_export_source(LocalExportSource::from_env());
    serve(server, rmcp::transport::stdio()).await
}

/// A boxed underlying error, kept so callers can walk the source chain.
type Cause = Box<dyn std::error::Error + Send + Sync>;

/// Failure while running the MCP server. The underlying cause is available
/// through [`std::error::Error::source`].
#[derive(Debug, thiserror::Error)]
pub enum ServeError {
    /// The server could not be configured, so it never started.
    #[error("MCP server could not be configured")]
    Configuration(#[source] Cause),
    /// The MCP initialization handshake failed.
    #[error("MCP initialization failed")]
    Initialize(#[source] Cause),
    /// The connection ended abnormally after initialization.
    #[error("MCP connection failed")]
    Connection(#[source] Cause),
}

async fn serve<T, E, A>(server: OsrsMcpServer, transport: T) -> Result<(), ServeError>
where
    T: IntoTransport<rmcp::RoleServer, E, A>,
    E: std::error::Error + Send + Sync + 'static,
{
    let running = server
        .serve(transport)
        .await
        .map_err(|error: ServerInitializeError| ServeError::Initialize(Box::new(error)))?;
    running
        .waiting()
        .await
        .map(|_| ())
        .map_err(|error| ServeError::Connection(Box::new(error)))
}

#[cfg(test)]
mod tests {
    use std::error::Error;

    use super::*;

    fn cause() -> Cause {
        Box::new(std::io::Error::other("pipe closed"))
    }

    #[test]
    fn each_serve_error_has_its_own_message_and_exposes_its_cause() {
        let errors = [
            (
                ServeError::Configuration(cause()),
                "MCP server could not be configured",
            ),
            (ServeError::Initialize(cause()), "MCP initialization failed"),
            (ServeError::Connection(cause()), "MCP connection failed"),
        ];
        for (error, message) in errors {
            assert_eq!(error.to_string(), message);
            let source = error.source().expect("every variant keeps its cause");
            assert_eq!(source.to_string(), "pipe closed");
        }
    }
}
