//! MCP adapter: exposes the library over the Model Context Protocol.
//!
//! This module is a thin transport layer. It holds no domain logic; tools
//! translate library values into protocol responses. All tools are advisory and
//! read-only.

use std::collections::BTreeMap;

use rmcp::{
    Json, ServerHandler, ServiceExt,
    handler::server::router::tool::ToolRouter,
    model::{ErrorData, Implementation, ServerCapabilities, ServerConfig},
    schemars::JsonSchema,
    serde_json,
    service::ServerInitializeError,
    tool, tool_handler, tool_router,
    transport::IntoTransport,
};
use serde::Serialize;

use crate::build_info;

/// Instructions shown to clients that surface server guidance.
const INSTRUCTIONS: &str = "Read-only advisory server for Old School RuneScape Hardcore \
worlds. It never performs in-game actions. Call `server_info` to see the version and \
capabilities.";

/// Structured result of the `server_info` tool.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, JsonSchema)]
#[schemars(crate = "rmcp::schemars")]
pub struct ServerInfoOutput {
    /// Server package name.
    pub name: String,
    /// Server package version (semantic version).
    pub version: String,
    /// Always true: the server never modifies game state or local data.
    pub read_only: bool,
    /// MCP capability groups this server provides, such as `tools`.
    pub capabilities: Vec<String>,
}

/// The OSRS MCP server.
#[derive(Debug, Clone)]
pub struct OsrsMcpServer {
    tool_router: ToolRouter<Self>,
}

impl Default for OsrsMcpServer {
    fn default() -> Self {
        Self::new()
    }
}

#[tool_router]
impl OsrsMcpServer {
    /// Creates a server with all tools registered.
    #[must_use]
    pub fn new() -> Self {
        Self {
            tool_router: Self::tool_router(),
        }
    }

    /// Reports this server's name, version, read-only guarantee and capabilities.
    #[tool(
        name = "server_info",
        description = "Report this server's name, version, read-only guarantee and MCP \
                       capabilities. Deterministic; uses no external data.",
        annotations(
            title = "Server information",
            read_only_hint = true,
            destructive_hint = false,
            idempotent_hint = true,
            open_world_hint = false
        )
    )]
    fn server_info() -> Result<Json<ServerInfoOutput>, ErrorData> {
        server_info_output()
            .map(Json)
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))
    }
}

/// The MCP capabilities this server advertises. This is the single source for
/// both the `initialize` response and the `server_info` tool, so they cannot
/// drift apart.
fn server_capabilities() -> ServerCapabilities {
    ServerCapabilities::builder().enable_tools().build()
}

/// Names of the capability groups declared in `capabilities`, sorted.
///
/// Derived from the serialised form, in which an undeclared group is omitted,
/// so a group added by a future rmcp release is reported without a code change.
///
/// # Errors
///
/// Returns an error if the capabilities do not serialise to a JSON object,
/// which would be a bug in the SDK. It is reported rather than turned into an
/// empty list, so `server_info` never under-reports.
fn capability_names(capabilities: &ServerCapabilities) -> Result<Vec<String>, serde_json::Error> {
    let groups: BTreeMap<String, serde_json::Value> =
        serde_json::from_value(serde_json::to_value(capabilities)?)?;
    Ok(groups.into_keys().collect())
}

/// Builds the `server_info` payload from compile-time package metadata.
fn server_info_output() -> Result<ServerInfoOutput, serde_json::Error> {
    let info = build_info();
    Ok(ServerInfoOutput {
        name: info.name.to_owned(),
        version: info.version.to_owned(),
        read_only: true,
        capabilities: capability_names(&server_capabilities())?,
    })
}

// The macro generates `async fn call_tool`/`list_tools` bodies that only
// delegate to the synchronous router; the lint cannot be satisfied in our code.
#[expect(
    clippy::unused_async_trait_impl,
    reason = "async trait methods are generated by rmcp's #[tool_handler] macro"
)]
#[tool_handler(router = self.tool_router)]
impl ServerHandler for OsrsMcpServer {
    fn get_info(&self) -> ServerConfig {
        let info = build_info();
        ServerConfig::new(server_capabilities())
            .with_server_info(Implementation::new(info.name, info.version))
            .with_instructions(INSTRUCTIONS)
    }
}

/// Serves MCP over the process's standard input and output until the client
/// disconnects.
///
/// Stdout carries protocol messages only; callers must send diagnostics to
/// stderr.
///
/// # Errors
///
/// Returns an error if the MCP handshake fails or the connection ends abnormally.
pub async fn serve_stdio() -> Result<(), ServeError> {
    let transport = rmcp::transport::stdio();
    serve(OsrsMcpServer::new(), transport).await
}

/// A boxed underlying error, kept so callers can walk the source chain.
type Cause = Box<dyn std::error::Error + Send + Sync>;

/// Failure while running the MCP server. The underlying cause is available
/// through [`std::error::Error::source`].
#[derive(Debug)]
pub enum ServeError {
    /// The MCP initialization handshake failed.
    Initialize(Cause),
    /// The connection ended abnormally after initialization.
    Connection(Cause),
}

impl std::fmt::Display for ServeError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Initialize(_) => "MCP initialization failed",
            Self::Connection(_) => "MCP connection failed",
        })
    }
}

impl std::error::Error for ServeError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Initialize(cause) | Self::Connection(cause) => Some(cause.as_ref()),
        }
    }
}

async fn serve<T, E, A>(server: OsrsMcpServer, transport: T) -> Result<(), ServeError>
where
    T: IntoTransport<rmcp::RoleServer, E, A>,
    E: std::error::Error + Send + Sync + 'static,
{
    let running = server
        .serve(transport)
        .await
        .map_err(|error: ServerInitializeError| ServeError::Initialize(Box::new(error)))?;
    running
        .waiting()
        .await
        .map(|_| ())
        .map_err(|error| ServeError::Connection(Box::new(error)))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(capabilities: &ServerCapabilities) -> Vec<String> {
        capability_names(capabilities).unwrap()
    }

    #[test]
    fn no_declared_capabilities_yield_no_names() {
        assert_eq!(names(&ServerCapabilities::default()), Vec::<String>::new());
    }

    #[test]
    fn declared_groups_are_named_and_undeclared_ones_are_not() {
        let tools_only = ServerCapabilities::builder().enable_tools().build();
        assert_eq!(names(&tools_only), ["tools"]);
    }

    #[test]
    fn every_declared_group_is_reported_including_ones_the_old_table_lacked() {
        let everything = ServerCapabilities::builder()
            .enable_tools()
            .enable_resources()
            .enable_prompts()
            .enable_completions()
            .enable_experimental()
            .build();
        assert_eq!(
            names(&everything),
            [
                "completions",
                "experimental",
                "prompts",
                "resources",
                "tools"
            ]
        );
    }

    #[test]
    fn the_server_advertises_only_the_tools_capability() {
        assert_eq!(names(&server_capabilities()), ["tools"]);
    }

    #[test]
    fn server_info_describes_this_package_as_read_only() {
        let info = build_info();
        let output = server_info_output().unwrap();
        assert_eq!(
            output,
            ServerInfoOutput {
                name: info.name.to_owned(),
                version: info.version.to_owned(),
                read_only: true,
                capabilities: vec!["tools".to_owned()],
            }
        );
    }
}
